"""make_lua_catalog.py <ink_catalog.json> <out NCInkCatalog.lua>: Lua data module for the tattoo library."""
import json, sys
cat = json.load(open(sys.argv[1]))
PRICE = {("Arm", "full"): 600, ("Arm", "upper"): 200, ("Arm", "lower"): 200, ("Leg", "full"): 450, ("Leg", "lower"): 200,
         ("Hand", "hand"): 150, ("Neck", "neck"): 200, ("Face", "face"): 150}
def price(it):
    p = PRICE[(it["area"], it["zone"])]
    t = it["tags"]
    if "half" in t or "forearm-sleeve" in t: p = 350
    if "band" in t: p = 120
    if it["colour"]: p += 50
    return p
L = ["--!nonstrict",
     "-- NCInkCatalog (ModuleScript in ReplicatedStorage): GENERATED by tools/ink/make_lua_catalog.py from ink_catalog.json.",
     "-- Every tattoo is an original, PG design (no gang names, numbers, symbols, weapons or bad words; words come",
     "-- from the fixed safe list below). area/zone say which ink layers a tattoo prints on (see NCInk.ZONES);",
     "-- files are the texture names per side (L/R for limbs, C for neck and face) that NCInkSetup maps to asset ids.",
     "local C = {}", "", "C.WORDS = {" + ", ".join(f'"{w}"' for w in cat["words"]) + "}", "", "C.ITEMS = {"]
for it in cat["items"]:
    files = ", ".join(f'{k} = "{v[:-4]}"' for k, v in it["files"].items())
    tags = ", ".join(f'"{t}"' for t in it["tags"])
    nm = it["name"].replace('"', '\\"')
    L.append(f'\t{{ id = "{it["id"]}", name = "{nm}", area = "{it["area"]}", zone = "{it["zone"]}", colour = {str(it["colour"]).lower()}, '
             f'price = {price(it)}, files = {{ {files} }}, tags = {{ {tags} }} }},')
L += ["}", "", "C.BY_ID = {}", "for _, it in ipairs(C.ITEMS) do", "\tC.BY_ID[it.id] = it", "end", "", "return C", ""]
open(sys.argv[2], "w").write("\n".join(L))
print(len(cat["items"]), "items")
